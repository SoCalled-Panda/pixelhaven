# ----------------------------------------------------------------- helpers

def hz(midi):
    return 440.0 * (2.0 ** ((midi - 69) / 12.0))


def normalize(samples, peak=0.82):
    m = max(1e-9, max(abs(s) for s in samples))
    k = peak / m
    return [s * k for s in samples]


def one_pole_lowpass(samples, cutoff):
    a = 1.0 - math.exp(-2.0 * math.pi * cutoff / SR)
    out = []
    y = 0.0
    for x in samples:
        y += a * (x - y)
        out.append(y)
    return out


def one_pole_highpass(samples, cutoff):
    lp = one_pole_lowpass(samples, cutoff)
    return [s - l for s, l in zip(samples, lp)]


def seam_crossfade(samples, fade=0.35):
    """Make `samples` loop seamlessly: crossfade the tail into the head."""
    n = int(fade * SR)
    head = samples[:n]
    tail = samples[-n:]
    mixed = [head[i] * math.sqrt(i / n) + tail[i] * math.sqrt(1.0 - i / n) for i in range(n)]
    return mixed + samples[n:-n]


class Loop:
    """A mixing buffer exactly N samples long."""

    def __init__(self, n):
        self.n = n
        self.buf = [0.0] * n

    def add(self, start_s, samples, gain=1.0):
        start = int(start_s * SR)
        end = min(self.n, start + len(samples))
        for i in range(max(0, start), end):
            self.buf[i] += samples[i - start] * gain

    def mix(self, other, gain=1.0):
        for i in range(self.n):
            self.buf[i] += other.buf[i] * gain


# --------------------------------------------------------- instrument meat

def pad_tone(freq, dur, rng, level=1.0):
    """Soft choir-ish pad: detuned sines with slow attack/release."""
    n = int(dur * SR)
    out = [0.0] * n
    det = 1.0 + (rng.random() - 0.5) * 0.004
    for i in range(n):
        t = i / SR
        env = min(1.0, t / 0.5) * min(1.0, (dur - t) / 0.5)
        s = math.sin(2 * math.pi * freq * det * t)
        s += 0.35 * math.sin(2 * math.pi * freq * 2.0 * t)
        out[i] = s * env
    return one_pole_lowpass(out, 1800)


def epiano_note(freq, dur, level=1.0):
    """Rhodes-ish: sine + soft overtones with exponential decay."""
    n = int(dur * SR)
    out = [0.0] * n
    for i in range(n):
        t = i / SR
        env = math.exp(-2.6 * t) * min(1.0, t / 0.004)
        s = math.sin(2 * math.pi * freq * t)
        s += 0.4 * math.sin(2 * math.pi * freq * 2.0 * t) * math.exp(-4.0 * t)
        s += 0.12 * math.sin(2 * math.pi * freq * 4.0 * t) * math.exp(-7.0 * t)
        # gentle tremolo shimmer
        s *= 1.0 + 0.06 * math.sin(2 * math.pi * 4.6 * t)
        out[i] = s * env
    return one_pole_lowpass(out, 3400)


def music_note(freq, dur, level=1.0):
    """Music-box ping: near-sine with fast decay and a faint sparkle."""
    n = int(dur * SR)
    out = [0.0] * n
    for i in range(n):
        t = i / SR
        env = math.exp(-3.4 * t) * min(1.0, t / 0.002)
        s = math.sin(2 * math.pi * freq * t)
        s += 0.18 * math.sin(2 * math.pi * freq * 3.0 * t) * math.exp(-6.0 * t)
        out[i] = s * env
    return out


def pluck_note(freq, dur, level=1.0):
    """Mellow nylon-ish pluck: summed harmonics, fast decay, soft LP."""
    n = int(dur * SR)
    out = [0.0] * n
    for i in range(n):
        t = i / SR
        env = math.exp(-5.0 * t) * min(1.0, t / 0.002)
        s = math.sin(2 * math.pi * freq * t)
        s += 0.5 * math.sin(2 * math.pi * freq * 2 * t) * math.exp(-8 * t)
        s += 0.25 * math.sin(2 * math.pi * freq * 3 * t) * math.exp(-11 * t)
        out[i] = s * env
    return one_pole_lowpass(out, 2600)


def bass_note(freq, dur):
    n = int(dur * SR)
    out = [0.0] * n
    for i in range(n):
        t = i / SR
        env = math.exp(-1.6 * t) * min(1.0, t / 0.006) * min(1.0, (dur - t) / 0.08)
        out[i] = math.sin(2 * math.pi * freq * t) * env
    return out


def kick_hit():
    dur = 0.24
    n = int(dur * SR)
    out = [0.0] * n
    phase = 0.0
    for i in range(n):
        t = i / SR
        f = 42.0 + 95.0 * math.exp(-24.0 * t)
        phase += 2 * math.pi * f / SR
        env = math.exp(-9.0 * t)
        out[i] = math.sin(phase) * env
    return out


def snare_hit(rng):
    dur = 0.16
    n = int(dur * SR)
    out = [0.0] * n
    for i in range(n):
        t = i / SR
        env = math.exp(-16.0 * t)
        out[i] = (rng.random() * 2 - 1) * env
    return one_pole_lowpass(one_pole_highpass(out, 900), 5200)


def hat_hit(rng, open=False):
    dur = 0.09 if open else 0.04
    n = int(dur * SR)
    out = [0.0] * n
    for i in range(n):
        t = i / SR
        env = math.exp(-(30.0 if open else 55.0) * t)
        out[i] = (rng.random() * 2 - 1) * env
    return one_pole_highpass(out, 6500)


def vinyl_crackle(n, rng, density=0.00045):
    """Sparse pops with decaying tails + faint constant hiss."""
    out = [0.0] * n
    tail = [0.0] * 24
    for i in range(n):
        s = 0.0
        if rng.random() < density:
            amp = (rng.random() * 2 - 1) * (0.35 + 0.65 * rng.random())
            tail[0] = amp
        s += tail[0]
        for j in range(len(tail) - 1, 0, -1):
            tail[j] = tail[j - 1] * 0.72
        tail[0] *= 0.72
        out[i] = s
    hiss = [(rng.random() * 2 - 1) * 0.012 for _ in range(n)]
    hiss = one_pole_lowpass(hiss, 6000)
    return [c + h for c, h in zip(out, hiss)]


def rain_layer(n, rng, level=1.0):
    """Soft rain: wandering filtered noise + sparse droplet ticks."""
    body = [0.0] * n
    b = 0.0
    wander_phase = rng.random() * 6.28
    for i in range(n):
        t = i / SR
        wander = 0.75 + 0.25 * math.sin(2 * math.pi * 0.05 * t + wander_phase)
        b += 0.22 * ((rng.random() * 2 - 1) - b)
        body[i] = b * 2.2 * wander
    body = one_pole_lowpass(body, 2400)
    for _ in range(int(n / SR * 9)):  # droplet ticks
        pos = rng.randrange(n - 200)
        amp = 0.05 + rng.random() * 0.08
        for j in range(90):
            body[pos + j] += math.exp(-60 * j / SR) * (rng.random() * 2 - 1) * amp
    return [x * level for x in body]


def echo_bus(notes, n, time_s, feedback=0.34, tone=2600):
    """Simple feedback delay over a note bus for lofi space."""
    out = list(notes)
    d = int(time_s * SR)
    for i in range(d, n):
        out[i] += out[i - d] * feedback
    return one_pole_lowpass(out, tone)


# ------------------------------------------------------------ track builder

def build_track(rng, bpm, bars, chords, layers):
    beat = 60.0 / bpm
    loop = Loop(int(bars * 4 * beat * SR))
    pent = layers["pent"]
    melody_bus = Loop(loop.n)

    for bar in range(bars):
        chord = chords[bar % len(chords)]
        t0 = bar * 4 * beat
        # pad every bar
        if layers.get("pad"):
            for m in chord:
                loop.add(t0, pad_tone(hz(m), 4 * beat, rng), 0.05)
        # rhodes comping on swung offbeats
        if layers.get("comp"):
            for b in (1.5, 3.0, 3.5):
                m = chord[int(rng.random() * len(chord))]
                loop.add(t0 + b * beat, epiano_note(hz(m + 12), 1.6 * beat), 0.16)
        # bass
        if layers.get("bass"):
            root = chord[0] - 12
            loop.add(t0, bass_note(hz(root), 1.4 * beat), 0.30)
            if bar % 2 == 1:
                loop.add(t0 + 2.5 * beat, bass_note(hz(root + 7 if rng.random() < 0.4 else root), 1.0 * beat), 0.22)
        # arpeggio plucks
        if layers.get("arp"):
            step = 0.5
            k = 0
            b = 0.0
            while b < 4.0:
                if rng.random() < 0.75:
                    m = chord[k % len(chord)] + (12 if k % 4 >= 2 else 0)
                    melody_bus.add(t0 + b * beat, pluck_note(hz(m), 1.2 * beat), 0.22)
                k += 1
                b += step
        # sparse melody: 1-3 notes per bar from the pentatonic scale
        if layers.get("melody"):
            for _ in range(rng.randrange(1, 4)):
                b = rng.choice([0.0, 1.0, 1.5, 2.0, 3.0, 3.5])
                m = rng.choice(pent) + 12
                dur = rng.choice([0.5, 1.0, 1.5]) * beat
                voice = layers["melody"]
                melody_bus.add(t0 + b * beat, voice(hz(m), max(dur, 0.4)), 0.15)
        # drums
        if layers.get("drums"):
            swing = 0.10 * beat
            loop.add(t0, kick_hit(), 0.42)
            if bar % 2 == 1:
                loop.add(t0 + 2.5 * beat + swing, kick_hit(), 0.30)
            loop.add(t0 + 1.0 * beat, snare_hit(rng), 0.16)
            loop.add(t0 + 3.0 * beat, snare_hit(rng), 0.14)
            b = 0.0
            while b < 4.0:
                off = swing if (b * 2) % 2 == 1 else 0.0
                loop.add(t0 + b * beat + off, hat_hit(rng, open=(b == 3.5)), 0.10)
                b += 0.5

    if layers.get("melody_echo"):
        echoed = echo_bus(melody_bus.buf, loop.n, beat * 0.75)
        for i in range(loop.n):
            loop.buf[i] += echoed[i] * 0.9
    else:
        loop.mix(melody_bus, 1.0)

    # ambience beds
    if layers.get("rain"):
        rain = rain_layer(loop.n, rng)
        for i in range(loop.n):
            loop.buf[i] += rain[i] * 0.30
    if layers.get("crackle"):
        crackle = vinyl_crackle(loop.n, rng)
        for i in range(loop.n):
            loop.buf[i] += crackle[i]

    out = one_pole_lowpass(loop.buf, 7200)  # lofi warmth
    out = [math.tanh(s * 1.25) * 0.9 for s in out]
    return seam_crossfade(normalize(out, 0.78))


