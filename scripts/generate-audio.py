def write_wav(path, samples):
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        frames = b"".join(
            struct.pack("<h", max(-32767, min(32767, int(s * 32767)))) for s in samples
        )
        w.writeframes(frames)


def main():
    has_ffmpeg = shutil.which("ffmpeg") is not None
    OUT.mkdir(parents=True, exist_ok=True)
    tmp = Path(tempfile.mkdtemp())

    # Remove previous-generation ambience beds (review feedback: go lofi).
    keep = {t["id"] for t in TRACKS}
    for old in OUT.glob("*.ogg"):
        if old.stem not in keep:
            old.unlink()
            print(f"  removed old track: {old.name}")
    for old in OUT.glob("*.wav"):
        if old.stem not in keep:
            old.unlink()

    tracks_meta = []
    for spec in TRACKS:
        rng = random.Random(spec["seed"])  # deterministic output
        duration = spec["bars"] * 4 * (60.0 / spec["bpm"])
        samples = build_track(random.Random(spec["seed"]), spec["bpm"], spec["bars"], spec["chords"], spec["layers"])
        wav_path = tmp / f"{spec['id']}.wav"
        write_wav(wav_path, samples)
        if has_ffmpeg:
            ogg_path = OUT / f"{spec['id']}.ogg"
            subprocess.run(
                ["ffmpeg", "-y", "-loglevel", "error", "-i", str(wav_path),
                 "-c:a", "libvorbis", "-qscale:a", "4", str(ogg_path)],
                check=True,
            )
            filename = ogg_path.name
        else:
            shutil.copyfile(wav_path, OUT / f"{spec['id']}.wav")
            filename = f"{spec['id']}.wav"
        size_kb = (OUT / filename).stat().st_size // 1024
        print(f"  {filename:20} {size_kb:5d} KB  {spec['title']}  ({duration:.1f}s loop)")
        tracks_meta.append({
            "id": spec["id"],
            "title": spec["title"],
            "file": f"audio/{filename}",
            "description": spec["description"],
            "license": f"{LICENSE_NOTE} — MIT license.",
        })

    (OUT / "tracks.json").write_text(
        json.dumps({
            "schemaVersion": 1,
            "defaultTrackId": "rainy-window",
            "defaultVolume": 0.6,
            "tracks": tracks_meta,
        }, indent=2) + "\n"
    )
    shutil.rmtree(tmp, ignore_errors=True)
    print(f"wrote {OUT / 'tracks.json'} (ffmpeg: {'yes' if has_ffmpeg else 'no — WAV fallback'})")


if __name__ == "__main__":
    main()
